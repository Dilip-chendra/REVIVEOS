"""
ReviveAI -- 100K Reproducible Evaluation Script

IMPORTANT: This evaluates the ACTUAL ReviveAI decision pipeline.
The prediction is made by the same policy engine used in production --
NOT by the ground-truth labeling function.

We measure whether the policy engine's ALLOW/BLOCK decision matches
the independent ground-truth label.

Prediction logic:
  - Build a PolicyContext from each record (same fields the real API uses)
  - Call PolicyEngine.evaluate() -- the real deterministic engine
  - ALLOW decision  -> prediction = 1 (system thinks it is automatable)
  - BLOCK decision  -> prediction = 0 (system thinks it should be stopped)

Ground truth:
  - Label is the ground_truth field generated by ground_truth_label() in
    generate_dataset.py using independent rule criteria.

Limitation (documented honestly):
  Because both the prediction engine and the ground-truth oracle ultimately
  derive from the SAME underlying synthetic feature set, and because
  the policy engine's rules (retry limit, amount ceiling, opt-out, flagged)
  are DIRECTLY MIRRORED in the oracle rules, there is strong structural
  correlation. The F1/precision/recall numbers reflect internal consistency
  of the system's rules -- not independent real-world accuracy.
  This is clearly documented in METHODOLOGY.md.

Run: python backend/evaluation/evaluate_100k.py
"""

import json
import os
import sys
from datetime import datetime, timezone

# Add backend to path so we can import app modules
BACKEND_DIR = os.path.join(os.path.dirname(__file__), "..")
sys.path.insert(0, BACKEND_DIR)

from generate_dataset import main as generate_dataset, SEED, DATASET_SIZE


def predict(record: dict) -> int:
    """
    Run the ACTUAL ReviveAI policy engine on a record.
    Returns 1 if policy allows automation, 0 if it blocks.

    We map failure_type to the most likely action type for the policy check.
    This matches what the simulation router does.
    """
    from app.services.policy_engine import PolicyEngine, PolicyContext

    # Map failure type to likely recommended action
    action_map = {
        "gateway_failure":       "route_switch",
        "timeout":               "retry",
        "technical_failure":     "retry",
        "authentication_failure":"retry",
        "checkout_abandonment":  "send_reminder",
        "subscription_failure":  "sequence",
        "insufficient_funds":    "send_reminder",
        "expired_card":          "send_reminder",
    }
    action = action_map.get(record["failure_type"], "retry")

    ctx = PolicyContext(
        case_id=record["record_id"],
        action_type=action,
        amount_inr=record["amount_inr"],
        retry_count=record["retry_count"],
        consecutive_failures=record["consecutive_failures"],
        customer_opted_out=record["customer_opted_out"],
        last_action_at=None,   # no cooldown in batch eval (no previous actions)
        last_action_type=None,
        case_type=record["failure_type"],
        is_flagged_customer=record["is_flagged_customer"],
    )

    engine = PolicyEngine()
    result = engine.evaluate(ctx)
    return 1 if result.allowed else 0


def calculate_metrics(results: list[dict]) -> dict:
    """Calculate TP/TN/FP/FN and derived precision/recall/F1/accuracy."""
    TP = sum(1 for r in results if r["label"] == 1 and r["prediction"] == 1)
    TN = sum(1 for r in results if r["label"] == 0 and r["prediction"] == 0)
    FP = sum(1 for r in results if r["label"] == 0 and r["prediction"] == 1)
    FN = sum(1 for r in results if r["label"] == 1 and r["prediction"] == 0)

    precision = TP / (TP + FP) if (TP + FP) > 0 else 0.0
    recall    = TP / (TP + FN) if (TP + FN) > 0 else 0.0
    f1        = (2 * precision * recall / (precision + recall)
                 if (precision + recall) > 0 else 0.0)
    accuracy  = (TP + TN) / len(results) if results else 0.0

    return {
        "TP": TP, "TN": TN, "FP": FP, "FN": FN,
        "precision": round(precision, 4),
        "recall":    round(recall, 4),
        "f1":        round(f1, 4),
        "accuracy":  round(accuracy, 4),
        "n":         len(results),
    }


def main():
    eval_dir = os.path.dirname(__file__)
    dataset_path = os.path.join(eval_dir, "dataset_100k.jsonl")

    # Generate dataset if missing
    if not os.path.exists(dataset_path):
        print("Dataset not found -- generating...")
        generate_dataset()

    print("Loading dataset...")
    records = []
    with open(dataset_path, encoding="utf-8") as f:
        for line in f:
            records.append(json.loads(line))

    assert len(records) == DATASET_SIZE, f"Expected {DATASET_SIZE}, got {len(records)}"

    # Evaluate only the held-out eval split
    eval_records = [r for r in records if r["split"] == "eval"]
    print(f"Evaluating {len(eval_records):,} held-out records...")

    results = []
    for i, rec in enumerate(eval_records):
        pred = predict(rec)
        results.append({"label": rec["ground_truth"], "prediction": pred})
        if (i + 1) % 5000 == 0:
            print(f"  {i+1:,}/{len(eval_records):,}...")

    metrics = calculate_metrics(results)
    print(f"\nEvaluation Results ({len(eval_records):,} eval records):")
    print(f"  TP={metrics['TP']:,}  TN={metrics['TN']:,}  FP={metrics['FP']:,}  FN={metrics['FN']:,}")
    print(f"  Precision: {metrics['precision']:.4f}")
    print(f"  Recall:    {metrics['recall']:.4f}")
    print(f"  F1:        {metrics['f1']:.4f}")
    print(f"  Accuracy:  {metrics['accuracy']:.4f}")

    # Save results artifact
    output = {
        "dataset_size":       DATASET_SIZE,
        "eval_split_size":    len(eval_records),
        "seed":               SEED,
        "eval_split_ratio":   0.30,
        "generated_at":       datetime.now(timezone.utc).isoformat(),
        "methodology_version":"1.0",
        "TP":                 metrics["TP"],
        "TN":                 metrics["TN"],
        "FP":                 metrics["FP"],
        "FN":                 metrics["FN"],
        "precision":          metrics["precision"],
        "recall":             metrics["recall"],
        "f1":                 metrics["f1"],
        "accuracy":           metrics["accuracy"],
        "note": (
            "Ground truth and prediction both derive from synthetic features. "
            "High correlation is expected and documented. See METHODOLOGY.md."
        ),
    }

    results_path = os.path.join(eval_dir, "results_100k.json")
    with open(results_path, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2)
    print(f"\nResults saved: {results_path}")
    return output


if __name__ == "__main__":
    main()
